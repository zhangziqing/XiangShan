#!/usr/bin/env python3
"""Emit a small Storage adapter from a call descriptor.

The adapter has one prepare function, one read function per read call, one
query function per CAM query, and one optional snapshot. It forwards to the
Storage template; no per-slot function is generated.
"""
import argparse
import json
from pathlib import Path


def prepare_parameters(spec):
    parameters = ["reset"]
    prepare = spec["prepare"]
    for write in prepare.get("writes", []):
        parameters += [write["enable"], write["index"], write["value"]]
    for field in prepare.get("fields", []):
        parameters += [field["enable"], field["index"], field["offset"], field["width"], field["value"]]
    for cam in prepare.get("cam_writes", []):
        parameters += [cam["enable"], cam["key"], cam["value"]]
    for update in prepare.get("updates", []):
        parameters += [update["enable"], update["amount"]]
    return list(dict.fromkeys(parameters))


def render(spec):
    entries = spec["entries"]
    width = spec["width"]
    pending = spec["pending_writes"]
    prefix = spec["prefix"]
    initial = ", ".join(f"UINT64_C({value})" for value in spec["initial"])
    prepare = spec["prepare"]
    parameters = prepare_parameters(spec)

    lines = [
        "// Generated by storage_emit.py; edit storage.json instead.",
        '#include "storage.hpp"',
        "",
        "namespace {",
        "",
        f"constexpr size_t Entries = {entries};",
        f"constexpr unsigned Width = {width};",
        f"constexpr size_t PendingWrites = {pending};",
        "",
        "using Storage = storage_boundary::Storage<Entries, Width, PendingWrites>;",
        "",
        "Storage instance{{" + initial + "}};",
        "unsigned long long committed_epoch = 0;",
        "",
        "Storage& sync(unsigned long long epoch) {",
        f"  if (committed_epoch != epoch) {{",
        "    instance.commit();",
        "    committed_epoch = epoch;",
        "  }",
        "  return instance;",
        "}",
        "",
        "}  // namespace",
        "",
        f'extern "C" void {prefix}_prepare(',
    ]
    lines += [f"    unsigned long long {name}," for name in parameters]
    lines[-1] = lines[-1].rstrip(",")
    lines += [") {", "  auto& model = instance;", "  model.begin((reset & 1) != 0);"]

    for write in prepare.get("writes", []):
        lines += [
            f"  if (({write['enable']} & 1) != 0) {{",
            f"    model.write({write['index']}, {write['value']});",
            "  }",
        ]
    for field in prepare.get("fields", []):
        lines += [
            f"  if (({field['enable']} & 1) != 0) {{",
            f"    model.writeField({field['index']},",
            f"        {{static_cast<unsigned>({field['offset']}), static_cast<unsigned>({field['width']})}},",
            f"        {field['value']});",
            "  }",
        ]
    for cam in prepare.get("cam_writes", []):
        lines += [
            f"  if (({cam['enable']} & 1) != 0) {{",
            f"    model.camWrite([key = {cam['key']}](uint64_t entry) {{ return entry == key; }},",
            f"        {cam['value']});",
            "  }",
        ]
    for update in prepare.get("updates", []):
        lines += [
            f"  if (({update['enable']} & 1) != 0) {{",
            f"    model.update([amount = {update['amount']}](uint64_t entry) {{",
            "      return (entry + amount) & storage_boundary::mask(Width);",
            "    });",
            "  }",
        ]
    lines += ["}", ""]

    for read in spec.get("reads", []):
        lines += [
            f'extern "C" void {prefix}_{read["name"]}(',
            "    unsigned long long epoch, unsigned long long index, unsigned long long* out) {",
            "  *out = sync(epoch).read(index);",
            "}",
            "",
        ]

    for query in spec.get("queries", []):
        name = query["name"]
        key = query["key"]
        kind = query["kind"]
        predicate = f"[key = {key}](uint64_t entry) {{ return entry == key; }}"
        if kind == "camRead":
            max_hits = query["max_hits"]
            lines += [
                f'extern "C" void {prefix}_{name}(',
                "    unsigned long long epoch, unsigned long long key,",
                "    unsigned long long* out_value, unsigned long long* out_hit) {",
                f"  const auto hits = sync(epoch).camRead<{max_hits}>(",
                f"      {predicate});",
                "  *out_value = hits[0].value;",
                "  *out_hit = hits[0].hit ? 1 : 0;",
                "}",
                "",
            ]
        elif kind == "camHitVec":
            lines += [
                f'extern "C" void {prefix}_{name}(',
                "    unsigned long long epoch, unsigned long long key, unsigned long long* out_mask) {",
                "  const auto hits = sync(epoch).camHitVec(",
                f"      {predicate});",
                "  uint64_t mask = 0;",
                "  for (size_t index = 0; index < Entries; ++index) {",
                "    if (hits[index]) mask |= UINT64_C(1) << index;",
                "  }",
                "  *out_mask = mask;",
                "}",
                "",
            ]
        elif kind == "camHitIdx":
            lines += [
                f'extern "C" void {prefix}_{name}(',
                "    unsigned long long epoch, unsigned long long key, unsigned long long* out_indices) {",
                "  const auto indices = sync(epoch).camHitIdx(",
                f"      {predicate});",
                "  for (size_t index = 0; index < Entries; ++index) out_indices[index] = indices[index];",
                "}",
                "",
            ]
        else:
            raise ValueError(f"unsupported query kind: {kind}")

    if spec.get("snapshot", False):
        lines += [
            f'extern "C" void {prefix}_snapshot(unsigned long long epoch, unsigned long long* out) {{',
              "  const auto& model = sync(epoch);",
            "  for (size_t index = 0; index < Entries; ++index) out[index] = model.read(index);",
            "}",
            "",
        ]

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("descriptor", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if the output is stale")
    args = parser.parse_args()

    rendered = render(json.loads(args.descriptor.read_text()))
    if args.check:
        if not args.output.exists() or args.output.read_text() != rendered:
            raise SystemExit(f"stale generated file: {args.output}")
        return
    args.output.write_text(rendered)


if __name__ == "__main__":
    main()
